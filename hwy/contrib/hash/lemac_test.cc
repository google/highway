template <size_t kStripes>
void CheckGolden(const uint8_t (*expected)[kHashBytes]) {
  uint8_t key[LeMac::kKeyBytes];
  uint8_t nonce[LeMac::kNonceBytes];
  FillIota(key, LeMac::kKeyBytes);
  FillIota(nonce, LeMac::kNonceBytes);
  std::vector<uint8_t> in(kGoldenSizes[kNumGolden - 1]);
  for (size_t i = 0; i < in.size(); ++i) {
    in[i] = static_cast<uint8_t>(i * 7 + 3);
  }
  const LeMacKey<kStripes> lemac_key(key);
  for (size_t i = 0; i < kNumGolden; ++i) {
    const size_t size = kGoldenSizes[i];
    if (size != 0) {
      uint8_t out[kHashBytes];
      LeMacHash(lemac_key, nonce, in.data(), size, out);
      HWY_ASSERT_ARRAY_EQ(expected[i], out, kHashBytes);
    }

    // The result must not depend on the vector size. Wide vectors are useful
    // for test coverage even where the default is narrower.
    HashBytes out16 = HashWith<kStripes, CappedTag<uint8_t, 16> >(
        lemac_key, nonce, in.data(), size);
    HWY_ASSERT_ARRAY_EQ(expected[i], out16.data(), kHashBytes);
    HashBytes out_wide = HashWith<kStripes, CappedTag<uint8_t, 16 * kStripes> >(
        lemac_key, nonce, in.data(), size);
    HWY_ASSERT_ARRAY_EQ(expected[i], out_wide.data(), kHashBytes);
  }
}

void TestGolden() {
  CheckGolden<1>(kGoldenX1);
  CheckGolden<2>(kGoldenX2);
}

// Any sequence of Update calls must match one-shot hashing.
template <size_t kStripes>
void CheckUpdate() {
  using Hasher = LeMacHasher<kStripes>;
  constexpr size_t kUpdateBytes = Hasher::kUpdateBytes;
  uint8_t key[LeMac::kKeyBytes];
  uint8_t nonce[LeMac::kNonceBytes];
  FillRandom(key, LeMac::kKeyBytes, 123);
  FillRandom(nonce, LeMac::kNonceBytes, 456);
  const LeMacKey<kStripes> lemac_key(key);
  constexpr size_t kBlocks = 5;
  std::vector<uint8_t> in(kBlocks * kUpdateBytes + 300);
  FillRandom(in.data(), in.size(), 789);

  Hasher reused(lemac_key);
  for (size_t tail : {size_t{0}, size_t{1}, size_t{300}}) {
    const size_t size = kBlocks * kUpdateBytes + tail;
    uint8_t expected[kHashBytes];
    LeMacHash(lemac_key, nonce, in.data(), size, expected);

    // Blocks per Update call.
    for (size_t piece : {size_t{1}, size_t{2}, size_t{3}, kBlocks}) {
      Hasher hasher(lemac_key);
      for (size_t block = 0; block < kBlocks; block += piece) {
        hasher.Update(in.data() + block * kUpdateBytes,
                      HWY_MIN(piece, kBlocks - block) * kUpdateBytes);
      }
      uint8_t actual[kHashBytes];
      hasher.Finalize(in.data() + kBlocks * kUpdateBytes, tail, nonce, actual);
      HWY_ASSERT_ARRAY_EQ(expected, actual, kHashBytes);
    }

    // Finalize can also absorb whole blocks, and Reset allows reuse.
    reused.Reset();
    reused.Update(in.data(), kUpdateBytes);
    uint8_t actual[kHashBytes];
    reused.Finalize(in.data() + kUpdateBytes, size - kUpdateBytes, nonce,
                    actual);
    HWY_ASSERT_ARRAY_EQ(expected, actual, kHashBytes);
  }
}

void TestUpdate() {
  CheckUpdate<1>();
  CheckUpdate<2>();
}

void AssertDistinct(std::vector<HashBytes>& hashes) {
  std::sort(hashes.begin(), hashes.end());
  HWY_ASSERT(std::adjacent_find(hashes.begin(), hashes.end()) == hashes.end());
}

// Various changes to the input, nonce or key must change the hash. Even a
// single collision among these few hashes would indicate a bug.
template <size_t kStripes>
void CheckDistinct() {
  uint8_t key[LeMac::kKeyBytes];
  uint8_t nonce[LeMac::kNonceBytes];
  FillRandom(key, LeMac::kKeyBytes, 1234);
  FillRandom(nonce, LeMac::kNonceBytes, 5678);
  const LeMacKey<kStripes> lemac_key(key);
  std::vector<uint8_t> in(300);
  FillRandom(in.data(), in.size(), 9012);
  const HashBytes original = HashWith(lemac_key, nonce, in.data(), in.size());
  std::vector<HashBytes> hashes;

  // Flipping any single bit of the input.
  hashes.push_back(original);
  for (size_t bit = 0; bit < in.size() * 8; ++bit) {
    const uint8_t mask = static_cast<uint8_t>(1u << (bit % 8));
    in[bit / 8] ^= mask;
    hashes.push_back(HashWith(lemac_key, nonce, in.data(), in.size()));
    in[bit / 8] ^= mask;
  }
  AssertDistinct(hashes);

  // Swapping adjacent 16-byte blocks, which belong to different stripes.
  hashes.clear();
  hashes.push_back(original);
  for (size_t pos = 0; pos + 32 <= in.size(); pos += 16) {
    const auto it = in.begin() + static_cast<ptrdiff_t>(pos);
    std::swap_ranges(it, it + 16, it + 16);
    hashes.push_back(HashWith(lemac_key, nonce, in.data(), in.size()));
    std::swap_ranges(it, it + 16, it + 16);
  }
  AssertDistinct(hashes);

  // All prefixes of {1, 0, 0, ..}: the padding must be injective.
  hashes.clear();
  std::vector<uint8_t> one_zeros(300, 0);
  one_zeros[0] = 1;
  for (size_t size = 0; size <= one_zeros.size(); ++size) {
    hashes.push_back(HashWith(lemac_key, nonce, one_zeros.data(), size));
  }
  AssertDistinct(hashes);

  // Flipping any single bit of the nonce or key.
  hashes.clear();
  hashes.push_back(original);
  for (size_t bit = 0; bit < 128; ++bit) {
    const uint8_t mask = static_cast<uint8_t>(1u << (bit % 8));
    nonce[bit / 8] ^= mask;
    hashes.push_back(HashWith(lemac_key, nonce, in.data(), in.size()));
    nonce[bit / 8] ^= mask;

    key[bit / 8] ^= mask;
    const LeMacKey<kStripes> other_key(key);
    hashes.push_back(HashWith(other_key, nonce, in.data(), in.size()));
    key[bit / 8] ^= mask;
  }
  AssertDistinct(hashes);
}

void TestDistinct() {
  CheckDistinct<1>();
  CheckDistinct<2>();
}

