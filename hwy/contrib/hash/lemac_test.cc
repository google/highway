constexpr size_t kHashBytes = LeMac::kHashBytes;
using HashBytes = std::array<uint8_t, kHashBytes>;

void FillIota(uint8_t* bytes, size_t size) {
  for (size_t i = 0; i < size; ++i) bytes[i] = static_cast<uint8_t>(i);
}

void FillRandom(uint8_t* bytes, size_t size, uint64_t seed) {
  uint64_t x = seed;
  for (size_t i = 0; i < size; ++i) {
    x ^= x << 13;  // xorshift64
    x ^= x >> 7;
    x ^= x << 17;
    bytes[i] = static_cast<uint8_t>(x >> 56);
  }
}

// Hashes `size` bytes (possibly zero) with absorption vectors `D`, using
// Update for all whole multiples of kUpdateBytes.
template <size_t kStripes, class D = LeMac::DefaultD<kStripes> >
HashBytes HashWith(const LeMacKey<kStripes>& key, const uint8_t* nonce,
                   const uint8_t* in, size_t size) {
  LeMacHasher<kStripes, D> hasher(key);
  constexpr size_t kUpdateBytes = LeMacHasher<kStripes, D>::kUpdateBytes;
  const size_t whole = size / kUpdateBytes * kUpdateBytes;
  if (whole != 0) hasher.Update(in, whole);
  HashBytes out;
  hasher.Finalize(in + whole, size - whole, nonce, out.data());
  return out;
}

// Test vectors of the corrected LeMac, from the authors' reference
// implementation (test_vectors.py, which also verifies lemac.c).
void TestOfficialVectors() {
  constexpr uint8_t kExpected[3][kHashBytes] = {
      {0x52, 0x28, 0x2E, 0x85, 0x3C, 0x9C, 0xFE, 0xB5, 0x53, 0x7D, 0x33, 0xFB,
       0x91, 0x6A, 0x34, 0x1F},
      {0x26, 0xFA, 0x47, 0x1B, 0x77, 0xFA, 0xCC, 0x73, 0xEC, 0x2F, 0x9B, 0x50,
       0xBB, 0x1A, 0xF8, 0x64},
      {0xD5, 0x8D, 0xFD, 0xBE, 0x8B, 0x02, 0x24, 0xE1, 0xD5, 0x10, 0x6A, 0xC4,
       0xD7, 0x75, 0xBE, 0xEF}};
  uint8_t key[LeMac::kKeyBytes] = {0};
  uint8_t nonce[LeMac::kNonceBytes] = {0};
  uint8_t in[65] = {0};
  uint8_t out[kHashBytes];

  // All-zero key, nonce and 0 or 16 input bytes. LeMacHash does not support
  // empty inputs, but Finalize does.
  const LeMacKey<1> zero_key(key);
  HWY_ASSERT_ARRAY_EQ(kExpected[0], HashWith(zero_key, nonce, in, 0).data(),
                      kHashBytes);
  LeMacHash(zero_key, nonce, in, 16, out);
  HWY_ASSERT_ARRAY_EQ(kExpected[1], out, kHashBytes);

  // Key, nonce and the 65 input bytes are 0, 1, 2, ...
  FillIota(key, LeMac::kKeyBytes);
  FillIota(nonce, LeMac::kNonceBytes);
  FillIota(in, sizeof(in));
  const LeMacKey<1> iota_key(key);
  LeMacHash(iota_key, nonce, in, sizeof(in), out);
  HWY_ASSERT_ARRAY_EQ(kExpected[2], out, kHashBytes);
}

